"""Emit the C++ HOTRG table from Exact_Solution's canonical decimal fixture."""
import argparse
import hashlib
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('input', type=Path, help='Exact_Solution/tests/data/ising_reference_high_precision.json')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
raw = args.input.read_bytes()
source_sha256 = hashlib.sha256(raw).hexdigest()
if source_sha256 != '01e8346519641e6f83c8a1eac0127b06e2b5497b081f8dd5bc058714dab112aa':
    parser.error('fixture differs from the pinned source; update its commit and SHA256 before regenerating')
data = json.loads(raw)
if data['format_version'] != 1 or data['significant_digits'] != 100:
    raise ValueError('expected version 1 with 100 significant digits')
lines = [
    '// Generated by scripts/generate_hotrg_reference.py; do not edit the values.',
    '// Source: pcchen/Exact_Solution PR #1, commit 1361a14aa978908bee8f82ac8f50d9ad9e2f466d.',
    '// tests/data/ising_reference_high_precision.json; 140/180 dps verified, 100 significant digits.',
    '// Source SHA256: ' + source_sha256,
    '// X = (E-E0) n/(2 pi), with exact rational T/Tc. Parse directly at the target precision.',
    '#pragma once', '#include <span>', '#include <string_view>', '#include <uni20/core/scalar_io.hpp>',
    '', 'namespace uni20::examples::dense_hotrg::reference', '{',
    'struct strip', '{',
    '    int log2_width;', '    int sites;', '    int numerator;', '    int denominator;',
    '    std::span<std::string_view const> scaling_dimensions;', '};', '',
    '// clang-format off',
]
entries = []
for case in data['cases']:
    sites = case['sites']
    if sites <= 0 or sites & (sites - 1):
        raise ValueError('width must be a power of two')
    num, den = map(int, case['temperature_over_tc'].split('/'))
    name = f'x_n{sites}_r{num}_{den}'
    lines.append(f'inline constexpr std::string_view {name}[] = {{')
    for value in case['X']:
        if not isinstance(value, str):
            raise ValueError('reference values must be decimal strings')
        lines.append('    ' + json.dumps(value) + ',')
    lines.append('};')
    entries.append(f'    {{{sites.bit_length()-1}, {sites}, {num}, {den}, {name}}},')
lines += ['inline constexpr strip strips[] = {', *entries, '};', '// clang-format on', '''
template <uni20::Real R> R value(std::string_view text, uni20::Precision p)
{
  if constexpr (requires { uni20::parse_real<R>(text, p); })
    return uni20::parse_real<R>(text, p);
  else
    return uni20::parse_real<R>(text);
}
template <uni20::Real R> strip const* find(int exponent, R const& ratio)
{
  auto const p = uni20::precision_of(ratio);
  for (auto const& candidate : strips)
    if (candidate.log2_width == exponent &&
        ratio == uni20::scalar_at_precision<R>(candidate.numerator, p) / candidate.denominator)
      return &candidate;
  return nullptr;
}
} // namespace uni20::examples::dense_hotrg::reference
''']
output = Path(__file__).resolve().parents[1] / 'examples/models/ising_strip_reference.hpp'
text = '\n'.join(lines)
if args.check:
    if output.read_text() != text:
        parser.exit(1, 'generated reference differs\n')
else:
    output.write_text(text)
