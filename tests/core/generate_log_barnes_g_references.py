"""Independent mpmath Barnes-G fixtures; not a build/test dependency.

Inputs are dyadic. Evaluate at 600 dps and serialize 400 digits. The largest
imaginary argument loses about 155 digits in the paired subtraction, leaving
more than 1024 reliable bits. Run from any directory.
"""
from pathlib import Path
import mpmath as mp

mp.mp.dps = 600
cases = [
    ("0.5", "0", "0.5"),
    ("0.25", "0.5", "0.5"),
    ("2", "3", "-0.25"),
    ("0.5", "15.5", "0.5"),
    ("0.5", "16", "0.5"),
    ("0.5", "16.5", "0.5"),
    ("0.5", "100", "0.5"),
    ("0.5", "1000000", "0.5"),
    ("32", "2", "4"),
    ("32", "2", "8"),
    ("0.5", "2", "64"),
    ("2", "1", mp.mpf(2)**-128),
    ("0.5", mp.mpf(2)**256, "0.5"),
    ("0.5", mp.mpf(2)**512, "0.5"),
    ("2", "3", mp.mpf(2)**-200),
    ("2", "3", -mp.mpf(2)**-200),
    (mp.mpf(2)**-80, "0", "0.5"),
    (mp.mpf(2)**-80, mp.mpf(2)**-40, "0.5"),
    ("1", "0.125", -1 + mp.mpf(2)**-20),
]
lines = [f"// Generated by generate_log_barnes_g_references.py; mpmath {mp.__version__}, 600 dps.",
         "#pragma once", "namespace uni20::test {",
         "struct log_barnes_g_reference { char const *re, *im, *shift, *value, *ratio; };",
         "inline constexpr log_barnes_g_reference log_barnes_g_references[] = {"]
for re, im, shift in cases:
    re, im, h = map(mp.mpf, (re, im, shift))
    z = mp.mpc(re, im)
    value = mp.log(abs(mp.barnesg(z)))
    ratio = mp.log(abs(mp.barnesg(z+h))) - value
    lines += ["  {" + ",\n   ".join('"'+mp.nstr(v, 400)+'"' for v in (re, im, h, value, ratio)) + "},"]
lines += ["};", "} // namespace uni20::test", ""]
Path(__file__).with_name("log_barnes_g_references.hpp").write_text("\n".join(lines))
