"""Regenerate generic log-Gamma fixtures with mpmath (not a test dependency).

All input components are dyadic and exactly representable by the tested families.
Evaluate at 800 decimal digits, serialize 400: subtraction in this independent
oracle still leaves >1024 reliable bits for the largest arguments/smallest shifts.
Run from any directory; only the adjacent fixture header is written.
"""
from pathlib import Path
import mpmath as mp

mp.mp.dps = 800
cases = [
    (mp.mpf("0.25"), mp.mpf("0.5"), mp.mpf("0.5")),
    (mp.mpf(2), mp.mpf(7), mp.mpf("-0.25")),
    (mp.mpf("0.5"), mp.mpf(80), mp.mpf("0.5")),
    (mp.mpf(35), mp.mpf(2), mp.mpf("0.5")),
    (mp.mpf("0.5"), mp.mpf(2)**256, mp.mpf("0.5")),
    (mp.mpf("0.5"), mp.mpf(2)**-256, mp.mpf("0.5")),
    (mp.mpf(2), mp.mpf(1), mp.mpf(2)**-128),
    (mp.mpf("0.5"), mp.mpf(2), mp.mpf(64)),
]
lines = [f"// Generated by generate_complex_log_gamma_references.py; mpmath {mp.__version__}, 800 dps.",
         "#pragma once", "namespace uni20::test {",
         "struct complex_log_gamma_reference { char const *re, *im, *shift, *gamma_re, *gamma_im, *ratio_re, *ratio_im; };",
         "inline constexpr complex_log_gamma_reference complex_log_gamma_references[] = {"]
for re, im, h in cases:
    z = mp.mpc(re, im)
    g = mp.loggamma(z)
    ratio = mp.loggamma(z+h) - g
    row = [re, im, h, g.real, g.imag, ratio.real, ratio.imag]
    lines += ["  {" + ",\n   ".join('"'+mp.nstr(v, 400)+'"' for v in row) + "},"]
lines += ["};", "} // namespace uni20::test", ""]
Path(__file__).with_name("complex_log_gamma_references.hpp").write_text("\n".join(lines))
